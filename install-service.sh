#!/usr/bin/env bash
# Install Kawari Web as a rootless systemd user service that comes back after a
# crash, a logout and a reboot.
#
#   ./install-service.sh            install and start
#   ./install-service.sh --remove   stop, disable and remove the unit
#
# "restart unless stopped" maps onto systemd as Restart=always: systemd brings it
# back whenever it exits, and `systemctl --user stop` keeps it stopped until you
# start it again.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

IMAGE="${IMAGE:-kawari-web}"
NAME="${NAME:-kawari-web}"
PORT="${PORT:-7301}"
DATA_DIR="${DATA_DIR:-$HOME/.kawari}"
SOCKET="${SOCKET:-/run/user/$(id -u)/podman/podman.sock}"
UNIT_DIR="$HOME/.config/containers/systemd"
UNIT="$UNIT_DIR/${NAME}.container"
FALLBACK_UNIT="$HOME/.config/systemd/user/${NAME}.service"

say()  { printf '\n\033[1m%s\033[0m\n' "$*"; }
warn() { printf '  ! %s\n' "$*" >&2; }
ok()   { printf '  - %s\n' "$*"; }

# ── remove ──────────────────────────────────────────────────────────────────
if [[ "${1:-}" == "--remove" ]]; then
    say "Removing the $NAME service"
    systemctl --user disable --now "$NAME" 2>/dev/null || true
    systemctl --user disable --now "${NAME}.service" 2>/dev/null || true
    rm -f "$UNIT" "$FALLBACK_UNIT"
    systemctl --user daemon-reload
    podman rm -f "$NAME" >/dev/null 2>&1 || true
    ok "unit files removed, container gone"
    ok "the image and $DATA_DIR were left alone"
    exit 0
fi

# ── checks ──────────────────────────────────────────────────────────────────
say "Checking the host"
command -v podman >/dev/null || { warn "podman is not installed"; exit 1; }
ok "$(podman --version)"

[[ -d "$DATA_DIR" ]] || { warn "$DATA_DIR does not exist - set DATA_DIR"; exit 1; }
[[ -w "$DATA_DIR" ]] || { warn "$DATA_DIR is not writable by $(id -un)"; exit 1; }
ok "data directory $DATA_DIR"

if ! grep -q "^$(id -un):" /etc/subuid 2>/dev/null; then
    warn "no /etc/subuid entry for $(id -un) - rootless podman needs one:"
    warn "    sudo usermod --add-subuids 100000-165535 --add-subgids 100000-165535 $(id -un)"
    warn "    podman system migrate"
    exit 1
fi
ok "subuid mapping present"

if [[ -S "$SOCKET" ]]; then
    ok "podman API socket at $SOCKET"
else
    warn "no podman socket at $SOCKET - the dashboard will not be able to start,"
    warn "  stop or build the game server. Enable it with:"
    warn "    systemctl --user enable --now podman.socket"
fi

# Quadlet ships with podman 4.4 and later; older hosts get a plain unit.
QUADLET=0
for generator in /usr/lib/systemd/user-generators/podman-user-generator \
                 /usr/libexec/podman/quadlet /usr/lib/systemd/system-generators/podman-system-generator; do
    [[ -e "$generator" ]] && QUADLET=1
done
[[ $QUADLET -eq 1 ]] && ok "quadlet support detected" || warn "no quadlet generator; using a plain systemd unit"

# ── keep it running after logout ────────────────────────────────────────────
say "Enabling linger"
if loginctl show-user "$(id -un)" 2>/dev/null | grep -q "Linger=yes"; then
    ok "already enabled"
else
    if loginctl enable-linger "$(id -un)" 2>/dev/null; then
        ok "enabled - user services now survive logout and start at boot"
    else
        warn "could not enable linger automatically. Without it the service stops"
        warn "  when you log out. Run: sudo loginctl enable-linger $(id -un)"
    fi
fi

# ── build ───────────────────────────────────────────────────────────────────
say "Building $IMAGE"
podman build -t "$IMAGE" --build-arg UID="$(id -u)" --build-arg GID="$(id -g)" \
    -f "$here/Containerfile" "$here"
ok "image built"

# A container left behind by run.sh would hold the port.
if podman container exists "$NAME" 2>/dev/null; then
    podman rm -f "$NAME" >/dev/null
    ok "removed the existing $NAME container"
fi

# ── unit ────────────────────────────────────────────────────────────────────
say "Installing the service"
socket_lines=""
if [[ -S "$SOCKET" ]]; then
    socket_lines="Volume=${SOCKET}:/run/podman.sock
Environment=PODMAN_SOCKET=/run/podman.sock"
fi

if [[ $QUADLET -eq 1 ]]; then
    mkdir -p "$UNIT_DIR"
    cat > "$UNIT" <<EOF
# Generated by install-service.sh. Edit and re-run: systemctl --user daemon-reload
[Unit]
Description=Kawari Web
After=network-online.target podman.socket
Wants=network-online.target

[Container]
Image=localhost/${IMAGE}
ContainerName=${NAME}
PublishPort=${PORT}:7301
# Maps your host uid to the same uid inside, so the mounted data directory is
# writable. Without it rootless podman maps to a subuid and /data is read-only.
UserNS=keep-id
# The advertised LAN address is not reachable from inside the container; podman
# exposes the host under this name instead.
AddHost=host.containers.internal:host-gateway
Volume=${DATA_DIR}:/data:z
# Podman runs on the host, so bind mounts this app asks for must be host paths.
Environment=KAWARI_HOST_DATA_DIR=${DATA_DIR}
${socket_lines}
# On SELinux hosts a confined container cannot reach the podman socket, which
# shows up as PermissionError [Errno 13]. Harmless where SELinux is absent.
SecurityLabelDisable=true

[Service]
# systemd's equivalent of --restart unless-stopped.
Restart=always
RestartSec=5

[Install]
WantedBy=default.target
EOF
    ok "wrote $UNIT"
    systemctl --user daemon-reload
    systemctl --user start "$NAME"
else
    mkdir -p "$(dirname "$FALLBACK_UNIT")"
    socket_args=""
    [[ -S "$SOCKET" ]] && socket_args="-v ${SOCKET}:/run/podman.sock -e PODMAN_SOCKET=/run/podman.sock"
    cat > "$FALLBACK_UNIT" <<EOF
[Unit]
Description=Kawari Web
After=network-online.target podman.socket
Wants=network-online.target

[Service]
Restart=always
RestartSec=5
TimeoutStartSec=300
ExecStartPre=-/usr/bin/podman rm -f ${NAME}
ExecStart=/usr/bin/podman run --rm --name ${NAME} \\
    --userns=keep-id \\
    --add-host=host.containers.internal:host-gateway \\
    -p ${PORT}:7301 \\
    -v ${DATA_DIR}:/data:z \\
    -e KAWARI_HOST_DATA_DIR=${DATA_DIR} \\
    ${socket_args} \\
    --security-opt label=disable \\
    localhost/${IMAGE}
ExecStop=/usr/bin/podman stop -t 10 ${NAME}

[Install]
WantedBy=default.target
EOF
    ok "wrote $FALLBACK_UNIT"
    systemctl --user daemon-reload
    systemctl --user enable --now "${NAME}.service"
fi

# ── verify ──────────────────────────────────────────────────────────────────
say "Verifying"
for _ in $(seq 1 30); do
    if curl -fsS "http://127.0.0.1:${PORT}/connect" >/dev/null 2>&1; then
        ok "answering on http://127.0.0.1:${PORT}"
        break
    fi
    sleep 1
done

systemctl --user status "$NAME" --no-pager --lines=0 2>/dev/null \
    || systemctl --user status "${NAME}.service" --no-pager --lines=0 2>/dev/null || true

if ! curl -fsS "http://127.0.0.1:${PORT}/connect" >/dev/null 2>&1; then
    warn "no answer yet on port ${PORT}. Check the log:"
    warn "    journalctl --user -u ${NAME} -n 40 --no-pager"
    exit 1
fi

LAN_IP=$(ip route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}' || true)
TS_IP=$(tailscale ip -4 2>/dev/null | head -1 || true)

say "Kawari Web is running as a service"
echo "  http://127.0.0.1:${PORT}"
for addr in $LAN_IP $TS_IP; do echo "  http://${addr}:${PORT}"; done
cat <<EOF

  Use the literal address, not localhost: localhost resolves to ::1 first and
  rootless podman publishes IPv4 only.

  systemctl --user status ${NAME}      how it is doing
  systemctl --user restart ${NAME}     restart it
  systemctl --user stop ${NAME}        stop it, and keep it stopped
  journalctl --user -u ${NAME} -f      follow the log
  ./install-service.sh --remove        undo all of this
EOF
